def add_para(doc, align=WD_ALIGN_PARAGRAPH.JUSTIFY, space_after=8, space_before=0,
             first_line_indent=None):
    p = doc.add_paragraph()
    set_rtl_bidi(p)
    p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    if first_line_indent is not None:
        p.paragraph_format.first_line_indent = Cm(first_line_indent)
    return p


def add_run(p, text, size=BODY_SIZE, bold=False):
    r = p.add_run(text)
    set_run_rtl_font(r, size=size, bold=bold)
    return r


def add_heading(doc, text, size=18, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER,
                 space_after=12, space_before=12, color=None):
    p = add_para(doc, align=align, space_after=space_after, space_before=space_before)
    r = add_run(p, text, size=size, bold=bold)
    if color:
        r.font.color.rgb = color
    return p


def add_rich_para(doc, segments, fm, size=BODY_SIZE, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
                   bold=False, first_line_indent=0.5, space_after=8):
    """segments: list of dicts:
       {'text': str, 'bold': bool (optional)} or
       {'fn': int, 'note': str}
    """
    p = add_para(doc, align=align, space_after=space_after, first_line_indent=first_line_indent)
    for seg in segments:
        if 'fn' in seg:
            fm.add_footnote(p, seg['fn'], seg['note'])
        else:
            add_run(p, seg['text'], size=size, bold=seg.get('bold', bold))
    return p


def add_simple_para(doc, text, **kwargs):
    return add_rich_para(doc, [{'text': text}], fm=kwargs.pop('fm'), **kwargs)


def set_page_setup(doc):
    section = doc.sections[0]
    section.page_height = Cm(29.7)
    section.page_width = Cm(21.0)
    section.top_margin = Cm(2.5)
    section.bottom_margin = Cm(2.5)
    section.left_margin = Cm(2.5)
    section.right_margin = Cm(2.5)
    sectPr = section._sectPr
    bidi = OxmlElement('w:bidi')
    sectPr.append(bidi)


def set_default_fonts(doc):
    styles = doc.styles
    normal = styles['Normal']
    normal.font.name = FONT_NAME
    normal.font.size = Pt(BODY_SIZE)
    rpr = normal.element.get_or_add_rPr()
    rFonts = rpr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rpr.append(rFonts)
    rFonts.set(qn('w:ascii'), FONT_NAME)
    rFonts.set(qn('w:hAnsi'), FONT_NAME)
    rFonts.set(qn('w:cs'), FONT_NAME)
    rFonts.set(qn('w:eastAsia'), FONT_NAME)
    szCs = OxmlElement('w:szCs')
    szCs.set(qn('w:val'), str(int(BODY_SIZE * 2)))
    rpr.append(szCs)
    pPr = normal.element.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    pPr.append(bidi)
    # document-wide default language
    docDefaults_rpr = doc.styles.element.find(qn('w:docDefaults'))


def divider(doc):
    p = add_para(doc, align=WD_ALIGN_PARAGRAPH.CENTER, space_after=12, space_before=6)
    add_run(p, "***", size=BODY_SIZE)


